async function runGit(args: string[], ctx: Ctx): Promise<void> {
  const { println, client, commitMessageRef, branch } = ctx;
  const sub = args[0];
  const store = useStore.getState();

  if (!sub) return println(c("red", "git: missing subcommand"));

  if (sub === "status") {
    const drafts = Object.values(store.drafts) as FileDraft[];
    if (drafts.length === 0) {
      println(c("green", `On branch ${branch}`));
      println(c("green", "nothing to commit, working tree clean"));
      return;
    }
    println(c("green", `On branch ${branch}`));
    println(c("cyan", "Changes not staged:"));
    for (const d of drafts) {
      const tag =
        d.status === "added"
          ? c("green", "new file:")
          : d.status === "deleted"
            ? c("red", "deleted:")
            : c("yellow", "modified:");
      println(`  ${tag.padEnd(30)} ${d.path}`);
    }
    println();
    println(c("dim", "Push with Save/Push button in top bar."));
    return;
  }

  if (sub === "diff") {
    const drafts = Object.values(store.drafts) as FileDraft[];
    if (drafts.length === 0) return println(c("dim", "no changes"));
    for (const d of drafts) {
      println(c("bold", `diff -- ${d.path}`));
      if (d.status === "deleted") {
        println(c("red", `- deleted (${d.originalContent?.length ?? 0} B)`));
      } else if (d.status === "added") {
        println(c("green", `+ added (${d.content.length} B)`));
      } else {
        const a = (d.originalContent ?? "").split("\n").length;
        const b = d.content.split("\n").length;
        println(`${c("red", `-${a}`)} ${c("green", `+${b}`)}`);
      }
    }
    return;
  }

  if (sub === "log") {
    const rest = args.slice(1);
    const dashIdx = rest.indexOf("--");
    const pathArgs = dashIdx >= 0 ? rest.slice(dashIdx + 1) : [];
    const filePath = pathArgs[0] ? resolvePath(ctx.cwd, pathArgs[0]) : undefined;
    println(c("dim", "Fetching commits from GitHub…"));
    try {
      const commits = await client.listCommits(filePath, branch, 15);
      if (commits.length === 0) {
        println(c("dim", "(no commits)"));
        return;
      }
      for (const cm of commits) {
        const short = cm.sha.slice(0, 7);
        const dt = cm.date
          ? new Date(cm.date).toLocaleString(undefined, {
              dateStyle: "short",
              timeStyle: "short",
            })
          : "";
        println(
          `${c("yellow", short)}  ${c("dim", dt)}  ${c("cyan", cm.author)}`,
        );
        println(`           ${cm.message}`);
      }
      println();
      println(
        c("dim", `Type 'git show <sha>' to view details, or visit the commit URL.`),
      );
    } catch (err) {
      println(
        c("red", `git log failed: ${err instanceof Error ? err.message : "unknown"}`),
      );
    }
    return;
  }

  if (sub === "show") {
    const sha = args[1];
    if (!sha) return println(c("red", "git show: <sha> required"));
    println(c("dim", "Fetching commit from GitHub…"));
    try {
      const detail = await client.showCommit(sha);
      println(c("yellow", `commit ${detail.sha}`));
      println(`Author: ${detail.author}`);
      println(`Date:   ${detail.date}`);
      println(`URL:    ${detail.htmlUrl}`);
      println();
      println(`    ${detail.message.split("\n").join("\n    ")}`);
      println();
      if (detail.files.length > 0) {
        println(c("cyan", `${detail.files.length} file(s) changed:`));
        for (const f of detail.files.slice(0, 20)) {
          const color =
            f.status === "added"
              ? "green"
              : f.status === "removed"
                ? "red"
                : "yellow";
          println(
            `  ${c(color, f.status.padEnd(10))} ${f.filename}  ${c("green", `+${f.additions}`)} ${c("red", `-${f.deletions}`)}`,
          );
        }
      }
    } catch (err) {
      println(
        c("red", `git show failed: ${err instanceof Error ? err.message : "unknown"}`),
      );
    }
    return;
  }

  if (sub === "branch") {
    println(c("dim", "Fetching branches from GitHub…"));
    try {
      const list = await client.listBranches();
      for (const b of list) {
        println(b === branch ? c("green", `* ${b}`) : `  ${b}`);
      }
    } catch (err) {
      println(
        c("red", `git branch failed: ${err instanceof Error ? err.message : "unknown"}`),
      );
    }
    return;
  }

  if (sub === "remote") {
    if (args[1] === "-v" || !args[1]) {
      println(
        `origin\tgit@github.com:${client.owner}/${client.repo}.git (fetch)`,
      );
      println(
        `origin\tgit@github.com:${client.owner}/${client.repo}.git (push)`,
      );
    }
    return;
  }

  if (sub === "checkout") {
    const target = args[1];
    if (!target) return println(c("red", "git checkout <branch>"));
    if (!store.session) return;
    if (Object.keys(store.drafts).length > 0) {
      return println(c("red", "error: uncommitted changes — Save / Push first"));
    }
    useStore.getState().setSession({ ...store.session, branch: target });
    useStore.setState({
      drafts: {},
      originals: {},
      tabs: [],
      activePath: null,
      tree: [],
      treeLoaded: false,
      baseHeadSha: null,
      hydrated: false,
      hydratedFor: null,
      remoteChanged: false,
    });
    println(c("green", `Switched to branch '${target}'`));
    return;
  }

  if (sub === "add") {
    println(
      c(
        "dim",
        "RepoDeck tracks edits automatically. Use the Save/Push dialog to commit.",
      ),
    );
    return;
  }

  if (sub === "commit") {
    const mIdx = args.indexOf("-m");
    const msg =
      mIdx >= 0
        ? args
            .slice(mIdx + 1)
            .join(" ")
            .replace(/^["']|["']$/g, "")
        : "";
    commitMessageRef.current = msg;
    println(
      msg
        ? c(
            "yellow",
            `Commit message staged: "${msg}" — use Save/Push to create the commit.`,
          )
        : c("red", `usage: git commit -m "message"`),
    );
    return;
  }

  if (sub === "push") {
    println(
      c(
        "yellow",
        "Open the Save/Push dialog in the top bar to push changes to GitHub.",
      ),
    );
    return;
  }

  if (sub === "pull") {
    if (!store.session) return;
    println(c("dim", "Fetching latest branch head…"));
    try {
      const head = await client.getBranchHead(store.session.branch);
      useStore.getState().setBaseHeadSha(head.sha);
      useStore.getState().setRemoteChanged(false);
      println(c("green", `Updated base to ${head.sha.slice(0, 7)}`));
    } catch {
      println(c("red", "pull failed"));
    }
    return;
  }

  println(c("red", `git: '${sub}' is not supported`));
}

/* --------------------------------------------------------- */
/* gh                                                        */
/* --------------------------------------------------------- */
async function runGh(args: string[], ctx: Ctx): Promise<void> {
  const { println, client } = ctx;
  const sub = args[0];

  if (!sub) {
    println(c("red", "gh: missing subcommand (pr|issue|repo|release|whoami)"));
    return;
  }

  if (sub === "pr" && args[1] === "list") {
    const stateIdx = args.indexOf("--state");
    const state = (stateIdx >= 0 ? args[stateIdx + 1] : "open") as
      | "open"
      | "closed"
      | "all";
    println(c("dim", `Fetching pull requests (${state})…`));
    try {
      const prs = await client.listPullRequests(state);
      if (prs.length === 0) return println(c("dim", "(no pull requests)"));
      for (const pr of prs) {
        const badge = pr.draft ? c("dim", " draft") : "";
        println(
          `${c("yellow", `#${pr.number}`)} ${c(pr.state === "open" ? "green" : "red", pr.state.padEnd(6))} ${pr.title}${badge}`,
        );
        println(
          `  ${c("dim", `by ${pr.user} · ${pr.head} → ${pr.base} · ${pr.htmlUrl}`)}`,
        );
      }
    } catch (err) {
      println(
        c("red", `gh pr list failed: ${err instanceof Error ? err.message : "unknown"}`),
      );
    }
    return;
  }

  if (sub === "issue" && args[1] === "list") {
    const stateIdx = args.indexOf("--state");
    const state = (stateIdx >= 0 ? args[stateIdx + 1] : "open") as
      | "open"
      | "closed"
      | "all";
    println(c("dim", `Fetching issues (${state})…`));
    try {
      const issues = await client.listIssues(state);
      if (issues.length === 0) return println(c("dim", "(no issues)"));
      for (const i of issues) {
        println(
          `${c("yellow", `#${i.number}`)} ${c(i.state === "open" ? "green" : "red", i.state.padEnd(6))} ${i.title}`,
        );
        println(
          `  ${c("dim", `by ${i.user} · ${i.htmlUrl}${i.labels.length ? ` · [${i.labels.join(", ")}]` : ""}`)}`,
        );
      }
    } catch (err) {
      println(
        c("red", `gh issue list failed: ${err instanceof Error ? err.message : "unknown"}`),
      );
    }
    return;
  }

  if (sub === "release" && args[1] === "list") {
    println(c("dim", "Fetching releases…"));
    try {
      const rels = await client.listReleases();
      if (rels.length === 0) return println(c("dim", "(no releases)"));
      for (const r of rels) {
        const tags: string[] = [];
        if (r.draft) tags.push("draft");
        if (r.prerelease) tags.push("pre");
        println(
          `${c("yellow", r.tag)}${tags.length ? ` ${c("dim", `[${tags.join(",")}]`)}` : ""} ${r.name}`,
        );
        println(`  ${c("dim", `${r.author} · ${r.htmlUrl}`)}`);
      }
    } catch (err) {
      println(
        c("red", `gh release list failed: ${err instanceof Error ? err.message : "unknown"}`),
      );
    }
    return;
  }

  if (sub === "repo" && args[1] === "view") {
    try {
      const meta = await client.getRepo();
      println(c("bold", meta.fullName));
      if (meta.description) println(meta.description);
      println(c("dim", `stars: ${meta.stars} · default: ${meta.defaultBranch} · ${meta.private ? "private" : "public"}`));
      println(c("dim", meta.htmlUrl));
    } catch (err) {
      println(
        c("red", `gh repo view failed: ${err instanceof Error ? err.message : "unknown"}`),
      );
    }
    return;
  }

  if (sub === "whoami" || (sub === "auth" && args[1] === "status")) {
    try {
      const u = await client.getAuthenticatedUser();
      println(c("green", `✓ Logged in as ${u.login}`));
      if (u.name) println(`  Name: ${u.name}`);
    } catch (err) {
      println(
        c("red", `gh whoami failed: ${err instanceof Error ? err.message : "unknown"}`),
      );
    }
    return;
  }

  println(c("red", `gh: '${args.join(" ")}' is not supported`));
}

/* --------------------------------------------------------- */
/* Runtime per tab                                           */
/* --------------------------------------------------------- */
interface TabRuntime {
  term: XTerm;
  fit: FitAddon;
  cwd: string;
  history: string[];
  historyIndex: number;
  buffer: string;
  cleanup: () => void;
}

interface TabMeta {
  id: string;
  label: string;
}

function uid(): string {
  return Math.random().toString(36).slice(2, 10);
}

/* --------------------------------------------------------- */
/* Main component                                            */
/* --------------------------------------------------------- */
export function Terminal({ client }: { client: GithubClient }) {
  const setTerminalOpen = useStore((s) => s.setTerminalOpen);
  const [tabs, setTabs] = useState<TabMeta[]>(() => [
    { id: uid(), label: "zsh" },
  ]);
  const [activeId, setActiveId] = useState(tabs[0].id);
  const runtimeRef = useRef<Map<string, TabRuntime>>(new Map());

  function addTab() {
    const id = uid();
    setTabs((prev) => [...prev, { id, label: `zsh ${prev.length + 1}` }]);
    setActiveId(id);
  }

  function closeTab(id: string) {
    const rt = runtimeRef.current.get(id);
    rt?.cleanup();
    runtimeRef.current.delete(id);
    setTabs((prev) => {
      const next = prev.filter((t) => t.id !== id);
      if (next.length === 0) {
        const fresh = { id: uid(), label: "zsh" };
        setActiveId(fresh.id);
        return [fresh];
      }
      if (activeId === id) setActiveId(next[0].id);
      return next;
    });
  }

  return (
    <div className="flex h-full flex-col bg-[#0d1117]">
      {/* tab bar */}
      <div className="flex h-8 shrink-0 items-stretch overflow-x-auto border-b border-border bg-muted/20 text-xs scrollbar-thin">
        <div className="flex items-center gap-1 px-2 text-muted-foreground">
          <span className="size-1.5 rounded-full bg-emerald-500" />
          <span>terminal</span>
        </div>
        {tabs.map((tab) => (
          <div
            key={tab.id}
            className={`group flex shrink-0 items-center gap-1 border-r border-border px-2 transition-colors ${
              tab.id === activeId
                ? "bg-[#0d1117] text-foreground"
                : "text-muted-foreground hover:bg-accent/40"
            }`}
          >
            <button
              type="button"
              onClick={() => setActiveId(tab.id)}
              className="truncate"
            >
              {tab.label}
            </button>
            <button
              type="button"
              onClick={(e) => {
                e.stopPropagation();
                closeTab(tab.id);
              }}
              className="rounded p-0.5 opacity-0 hover:bg-accent group-hover:opacity-100"
              aria-label={`Close ${tab.label}`}
            >
              <X className="size-3" />
            </button>
          </div>
        ))}
        <button
          type="button"
          onClick={addTab}
          className="flex items-center px-2 text-muted-foreground hover:bg-accent/40"
          aria-label="New terminal"
        >
          <Plus className="size-3.5" />
        </button>
      </div>

      {/* terminal panels */}
      <div className="relative flex-1 min-h-0">
        {tabs.map((tab) => (
          <TerminalPanel
            key={tab.id}
            id={tab.id}
            visible={tab.id === activeId}
            client={client}
            runtimeRef={runtimeRef}
            onClose={() => setTerminalOpen(false)}
          />
        ))}
      </div>
    </div>
  );
}

/* --------------------------------------------------------- */
/* Panel per tab                                             */
/* --------------------------------------------------------- */
function TerminalPanel({
  id,
  visible,
  client,
  runtimeRef,
  onClose,
}: {
  id: string;
  visible: boolean;
  client: GithubClient;
  runtimeRef: React.MutableRefObject<Map<string, TabRuntime>>;
  onClose: () => void;
}) {
  const containerRef = useRef<HTMLDivElement>(null);
  const visibleRef = useRef(visible);
  visibleRef.current = visible;

  useEffect(() => {
    let cancelled = false;
    let localCleanup = () => {};

    (async () => {
      const [{ Terminal: XTermCtor }, { FitAddon }] = await Promise.all([
        import("@xterm/xterm"),
        import("@xterm/addon-fit"),
      ]);
      // @ts-expect-error side-effect CSS import
      await import("@xterm/xterm/css/xterm.css");

      if (cancelled || !containerRef.current) return;
      if (runtimeRef.current.has(id)) return;

      const term = new XTermCtor({
        fontFamily:
          "var(--font-jetbrains), 'JetBrains Mono', ui-monospace, monospace",
        fontSize: 12,
        lineHeight: 1.35,
        cursorBlink: true,
        theme: {
          background: "#0d1117",
          foreground: "#e6edf3",
          cursor: "#10b981",
          selectionBackground: "#10b98155",
          black: "#0d1117",
          red: "#f85149",
          green: "#3fb950",
          yellow: "#d29922",
          blue: "#58a6ff",
          magenta: "#bc8cff",
          cyan: "#56d4dd",
          white: "#e6edf3",
        },
        allowProposedApi: true,
        scrollback: 3000,
        convertEol: true,
      });

      const fit = new FitAddon();
      term.loadAddon(fit);
      term.open(containerRef.current);
      try {
        fit.fit();
      } catch {
        /* ignore */
      }

      const onResize = () => {
        try {
          fit.fit();
        } catch {
          /* ignore */
        }
      };
      window.addEventListener("resize", onResize);
      const observer = new ResizeObserver(onResize);
      observer.observe(containerRef.current);

      const rt: TabRuntime = {
        term,
        fit,
        cwd: "",
        history: [],
        historyIndex: -1,
        buffer: "",
        cleanup: () => {},
      };
      runtimeRef.current.set(id, rt);

      const prompt = () =>
        `${c("green", "repodeck")}${c("dim", "·")}${c("cyan", `/${rt.cwd || ""}`)}${c("dim", "$")} `;

      const writePrompt = () => term.write("\r\n" + prompt());
      const print = (t: string) => term.write(t);
      const println = (t?: string) => term.write((t ?? "") + "\r\n");

      const redrawLine = () => {
        term.write("\r\x1b[K" + prompt() + rt.buffer);
      };

      const clear = () => {
        term.clear();
        term.write(prompt());
      };

      const ctx: Ctx = {
        get cwd() {
          return rt.cwd;
        },
        setCwd: (n) => {
          rt.cwd = n;
        },
        print,
        println,
        clear,
        client,
        commitMessageRef: { current: "" },
        branch: useStore.getState().session?.branch ?? "main",
        closeTerminal: onClose,
      } as unknown as Ctx;
      // Ctx uses cwd as value; we need live access. Recreate per-command below.

      const makeCtx = (): Ctx => ({
        cwd: rt.cwd,
        setCwd: (n) => {
          rt.cwd = n;
        },
        print,
        println,
        clear,
        client,
        commitMessageRef: { current: "" },
        branch: useStore.getState().session?.branch ?? "main",
        closeTerminal: onClose,
      });
      void ctx;

      const run = async (line: string) => {
        const trimmed = line.trim();
        if (!trimmed) {
          writePrompt();
          return;
        }
        rt.history.push(trimmed);
        if (rt.history.length > 200) rt.history.shift();
        rt.historyIndex = rt.history.length;

        const tokens = tokenize(trimmed);
        const [name, ...args] = tokens;

        if (name === "history") {
          rt.history.forEach((h, i) => println(`${i + 1}  ${h}`));
          writePrompt();
          return;
        }

        if (name === "clear") {
          clear();
          return;
        }

        // Binary/packaged commands → help + download
        const NOT_SUPPORTED = [
          "npm",
          "node",
          "python",
          "python3",
          "pip",
          "pip3",
          "yarn",
          "pnpm",
          "bun",
          "deno",
          "go",
          "cargo",
          "rustc",
          "java",
          "javac",
          "ruby",
          "gem",
          "php",
        ];
        if (NOT_SUPPORTED.includes(name)) {
          println(
            c("yellow", `${name} is not available in this terminal (browser environment).`),
          );
          println(
            c("dim", "A shell script equivalent has been prepared for you."),
          );
          toast.info(`${name} is not runnable here`, {
            description: "Download a .sh script to run it locally.",
            action: {
              label: "Download",
              onClick: () => downloadShellCommand(trimmed),
            },
          });
          writePrompt();
          return;
        }

        const cmd = BUILTINS[name];
        if (!cmd) {
          println(c("red", `${name}: command not found. Type 'help'.`));
          writePrompt();
          return;
        }

        try {
          await cmd.run(args, makeCtx());
        } catch (err) {
          println(
            c(
              "red",
              `error: ${err instanceof Error ? err.message : "unknown"}`,
            ),
          );
        }
        writePrompt();
      };

      const tabComplete = () => {
        const parts = rt.buffer.split(/\s+/);
        const prefix = parts.pop() ?? "";
        const tree = useStore.getState().tree;

        if (parts.length === 0) {
          const matches = Object.keys(BUILTINS).filter((k) =>
            k.startsWith(prefix),
          );
          if (matches.length === 1) {
            rt.buffer = matches[0] + " ";
            redrawLine();
          } else if (matches.length > 1) {
            println();
            println(matches.join("  "));
            redrawLine();
          }
          return;
        }

        const parent = dirname(prefix);
        const baseName = basename(prefix);
        const targetDir = resolvePath(rt.cwd, parent);
        const dir = getDirNode(tree, targetDir);
        const children = dir?.children ?? [];
        const matches = children
          .filter((n) => n.name.startsWith(baseName))
          .map((n) => (n.type === "dir" ? `${n.name}/` : n.name));

        if (matches.length === 1) {
          const completed = parent ? `${parent}/${matches[0]}` : matches[0];
          rt.buffer = parts.join(" ") + " " + completed;
          redrawLine();
        } else if (matches.length > 1) {
          println();
          println(matches.join("  "));
          redrawLine();
        }
      };

      term.onData((data) => {
        for (let i = 0; i < data.length; i += 1) {
          const ch = data[i];

          if (ch === "\r") {
            term.write("\r\n");
            const line = rt.buffer;
            rt.buffer = "";
            void run(line);
            continue;
          }

          if (ch === "\x7f") {
            if (rt.buffer.length > 0) {
              rt.buffer = rt.buffer.slice(0, -1);
              redrawLine();
            }
            continue;
          }

          if (ch === "\t") {
            tabComplete();
            continue;
          }

          if (ch === "\x03") {
            println("^C");
            rt.buffer = "";
            writePrompt();
            continue;
          }

          if (ch === "\x1b") {
            if (data[i + 1] === "[" && data[i + 2] === "A") {
              i += 2;
              if (rt.historyIndex > 0) {
                rt.historyIndex -= 1;
                rt.buffer = rt.history[rt.historyIndex] ?? "";
                redrawLine();
              }
              continue;
            }
            if (data[i + 1] === "[" && data[i + 2] === "B") {
              i += 2;
              if (rt.historyIndex < rt.history.length - 1) {
                rt.historyIndex += 1;
                rt.buffer = rt.history[rt.historyIndex] ?? "";
              } else {
                rt.historyIndex = rt.history.length;
                rt.buffer = "";
              }
              redrawLine();
              continue;
            }
            i += 1;
            continue;
          }

          if (ch < " ") continue;

          rt.buffer += ch;
          term.write(ch);
        }
      });

      // banner
      println(c("bold", "RepoDeck terminal v2"));
      println(
        c(
          "dim",
          "Real git/gh commands hit GitHub. Type 'help' for the list.",
        ),
      );
      term.write(prompt());

      localCleanup = () => {
        window.removeEventListener("resize", onResize);
        observer.disconnect();
        term.dispose();
      };
      rt.cleanup = localCleanup;
    })();

    return () => {
      cancelled = true;
      localCleanup();
    };
  }, [id, client, runtimeRef, onClose]);

  useEffect(() => {
    if (!visible) return;
    const rt = runtimeRef.current.get(id);
    if (!rt) return;
    // schedule fit after paint
    requestAnimationFrame(() => {
      try {
        rt.fit.fit();
        rt.term.focus();
      } catch {
        /* ignore */
      }
    });
  }, [visible, id, runtimeRef]);

  return (
    <div
      ref={containerRef}
      className={visible ? "absolute inset-0 p-2" : "absolute inset-0 hidden"}
    />
  );
}
