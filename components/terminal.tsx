/* --------------------------------------------------------- */
/* Tokenizer                                                 */
/* --------------------------------------------------------- */
function tokenize(line: string): string[] {
  const out: string[] = [];
  let current = "";
  let quote: '"' | "'" | null = null;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (quote) {
      if (ch === quote) quote = null;
      else current += ch;
      continue;
    }
    if (ch === '"' || ch === "'") {
      quote = ch;
      continue;
    }
    if (ch === " ") {
      if (current) {
        out.push(current);
        current = "";
      }
      continue;
    }
    current += ch;
  }
  if (current) out.push(current);
  return out;
}

/* --------------------------------------------------------- */
/* Download shell helper                                     */
/* --------------------------------------------------------- */
function downloadShellCommand(line: string) {
  const script = `#!/usr/bin/env bash
# Generated by RepoDeck — this command is not available in the browser terminal.
# Run it locally in your cloned repo.
set -e
${line}
`;
  const blob = new Blob([script], { type: "text/x-shellscript;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `repodeck-${line.split(/\s+/)[0]}-${Date.now()}.sh`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

