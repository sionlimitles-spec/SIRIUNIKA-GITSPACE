/* --------------------------------------------------------- */
/* ANSI helpers                                              */
/* --------------------------------------------------------- */
const C = {
  reset: "\x1b[0m",
  bold: "\x1b[1m",
  dim: "\x1b[90m",
  red: "\x1b[31m",
  green: "\x1b[32m",
  yellow: "\x1b[33m",
  blue: "\x1b[34m",
  magenta: "\x1b[35m",
  cyan: "\x1b[36m",
  white: "\x1b[37m",
  gray: "\x1b[90m",
};

function c(code: keyof typeof C, text: string): string {
  return `${C[code]}${text}${C.reset}`;
}

/* --------------------------------------------------------- */
/* Path helpers                                              */
/* --------------------------------------------------------- */
function resolvePath(cwd: string, input: string): string {
  if (!input) return cwd;
  const raw = input.startsWith("/") ? input.slice(1) : `${cwd}/${input}`;
  const stack: string[] = [];
  for (const part of raw.split("/")) {
    if (!part || part === ".") continue;
    if (part === "..") stack.pop();
    else stack.push(part);
  }
  return stack.join("/");
}

function getDirNode(tree: TreeNode[], cwd: string): TreeNode | null {
  if (!cwd) return { name: "", path: "", type: "dir", children: tree };
  const node = findNode(tree, cwd);
  return node && node.type === "dir" ? node : null;
}

